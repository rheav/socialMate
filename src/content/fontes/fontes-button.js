  /** The photo under the pointer: big enough, with an address the worker can fetch. Over the pill, the current one. */
  function photoAt() {
    for (const el of document.elementsFromPoint(x, y)) {
      if (el === host) return target;
      if (el.tagName !== "IMG") continue;
      const r = el.getBoundingClientRect();
      if (r.width >= FONTES_MIN_SIDE && r.height >= FONTES_MIN_SIDE && fontesBestUrl(el.srcset, el.currentSrc || el.src)) return el;
    }
    return null;
  }

  function update() {
    frame = 0;
    if (disabled) return;
    if (!busy && x >= 0) target = photoAt();
    place();
  }

  /** In the photo's top-right corner, kept inside the viewport while the photo scrolls. */
  function place() {
    const r = target && target.isConnected ? target.getBoundingClientRect() : null;
    const top = r ? Math.max(r.top, 0) + 10 : 0;
    if (!r || r.bottom < 40 || r.top > innerHeight || top > r.bottom - 40) { pill.hidden = true; return; }
    pill.style.left = `${Math.min(r.right, innerWidth) - 10}px`;
    pill.style.top = `${top}px`;
    pill.hidden = false;
  }

  function set(state, text) {
    pill.dataset.state = state;
    label.textContent = text;
  }

  /** The post the photo belongs to: its permalink on a feed card, else the page itself. */
  function postLink(img) {
    const a = img.closest("article")?.querySelector('a[href*="/p/"], a[href*="/reel/"]') ||
      img.closest('a[href*="/p/"], a[href*="/reel/"], a[href*="/photo/"], a[href*="/video/"]');
    return a ? a.href : location.href;
  }

  // The page must not see a press on the pill (Instagram likes a photo on double-tap, closes viewers on click).
  for (const type of ["pointerdown", "mousedown", "mouseup", "dblclick"]) pill.addEventListener(type, (e) => e.stopPropagation());
  pill.addEventListener("click", (e) => {
    e.preventDefault();
    e.stopPropagation();
    const url = target && fontesBestUrl(target.srcset, target.currentSrc || target.src);
    if (!url || busy) return;
    busy = true;
    clearTimeout(reset);
    set("sending", "Enviando…");
    const done = (state, text) => {
      busy = false;
      set(state, text);
      reset = setTimeout(() => { set("idle", "Fontes"); schedule(); }, 2600);
    };
    try {
      chrome.runtime.sendMessage({ type: "FBW_FONTES_SEND", url, origin: fontesOrigin(location.hostname), pageUrl: postLink(target) }, (res) => {
        if (chrome.runtime.lastError || !res) return done("fail", "Falhou");
        if (res.ok) return done("done", res.duplicate ? "Já estava nas Fontes" : "Nas Fontes");
        if (res.error === "app") return done("warn", "Abra o UGC Factory");
        done("fail", res.error === "fetch" ? "Não baixou a foto" : "Falhou");
      });
    } catch {
      done("fail", "Recarregue a página"); // this copy's chrome.* died with an extension reload
    }
  });

  function teardown() {
    document.removeEventListener("pointermove", onMove, { capture: true });
    window.removeEventListener("scroll", schedule, { capture: true });
    document.documentElement.removeEventListener("mouseleave", onLeave);
    cancelAnimationFrame(frame);
    clearTimeout(reset);
    host.remove();
  }
